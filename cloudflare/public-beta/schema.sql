PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS households (
 id TEXT PRIMARY KEY, write_hash TEXT NOT NULL UNIQUE, timezone TEXT NOT NULL,
 created INTEGER NOT NULL, disabled INTEGER NOT NULL DEFAULT 0,
 live_at TEXT, live_json TEXT, history_at TEXT, history_json TEXT
);
CREATE TABLE IF NOT EXISTS invites (hash TEXT PRIMARY KEY, expires INTEGER NOT NULL, used INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS pair_codes (hash TEXT PRIMARY KEY, tenant TEXT NOT NULL REFERENCES households(id) ON DELETE CASCADE, expires INTEGER NOT NULL, used INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS oauth_codes (hash TEXT PRIMARY KEY, tenant TEXT NOT NULL REFERENCES households(id) ON DELETE CASCADE, client TEXT NOT NULL, redirect TEXT NOT NULL, challenge TEXT, expires INTEGER NOT NULL, used INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS access_tokens (hash TEXT PRIMARY KEY, tenant TEXT NOT NULL REFERENCES households(id) ON DELETE CASCADE, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS refresh_tokens (hash TEXT PRIMARY KEY, tenant TEXT NOT NULL REFERENCES households(id) ON DELETE CASCADE, expires INTEGER NOT NULL);
